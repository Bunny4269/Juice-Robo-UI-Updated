import { useMemo } from "react";
import "./PaymentSuccessScreen.css";

/* =========================================================
   JUICE ROBO — FINAL PAYMENT SUCCESS SCREEN

   Shows ONLY:
   - Payment successful
   - 4-digit collection code
   - Collection instruction

   Does NOT show:
   - Order ID
   - Amount
   - UPI reference
   - Machine ID
   - Location
   - Customer information

   The collection code is NEVER generated by this component.
   It must come from the verified backend payment/order response.
   ========================================================= */

function clean(value) {
  return String(
    value ?? ""
  ).trim();
}

/* =========================================================
   COLLECTION CODE
   ========================================================= */

function getCollectionCode(
  order = {}
) {
  const candidates = [
    order?.collection_code,
    order?.collectionCode,
    order?.collection_pin,
    order?.collectionPin,
    order?.orderPin,
    order?.order_pin,
    order?.pickupCode,
    order?.pickup_code,

    order?.data?.collection_code,
    order?.data?.collectionCode,
    order?.data?.collection_pin,
    order?.data?.collectionPin,
    order?.data?.orderPin,
    order?.data?.order_pin,
    order?.data?.pickupCode,
    order?.data?.pickup_code,

    order?.result?.collection_code,
    order?.result?.collectionCode,
    order?.result?.collection_pin,
    order?.result?.collectionPin,
    order?.result?.orderPin,
    order?.result?.order_pin,
    order?.result?.pickupCode,
    order?.result?.pickup_code,
  ];

  for (const candidate of candidates) {
    const raw =
      clean(candidate);

    /*
     * Direct four-digit value.
     */
    if (
      /^\d{4}$/.test(raw)
    ) {
      return raw;
    }

    /*
     * Backend may wrap the code in text.
     */
    const match =
      raw.match(
        /\b(\d{4})\b/
      );

    if (
      match?.[1] &&
      /^\d{4}$/.test(
        match[1]
      )
    ) {
      return match[1];
    }
  }

  /*
   * Final fallback:
   * Read the verified code persisted by App.jsx.
   *
   * This is NOT generating a code.
   * It only restores the backend-provided value after refresh.
   */
  try {
    const storedCode =
      sessionStorage.getItem(
        "juice_robo_collection_code"
      );

    if (
      /^\d{4}$/.test(
        clean(storedCode)
      )
    ) {
      return clean(
        storedCode
      );
    }
  } catch {
    // Ignore storage errors.
  }

  return "";
}

/* =========================================================
   SUCCESS GIF
   ========================================================= */

function PaymentSuccessGif() {
  const gifSrc =
    `${import.meta.env.BASE_URL}assets/Payment-successful.gif`;

  return (
    <div
      className="jr-payment-success-animation"
      aria-hidden="true"
    >
      <img
        src={gifSrc}
        alt=""
        className="jr-payment-success-gif"
        draggable="false"
      />
    </div>
  );
}

/* =========================================================
   MAIN
   ========================================================= */

