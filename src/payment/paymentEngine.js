export function normalizePaymentFieldKey(key) {
  return String(key || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

/**
 * Safely parses query parameters from a UPI URI (upi://pay?...).
 * Handles HTML entities, standard encoding, and non-encoded characters.
 */
export function parseUpiUriParams(uri) {
  const params = {};
  if (!uri || typeof uri !== "string") return params;
  const clean = uri.trim().replace(/&amp;/gi, "&");
  const qIndex = clean.indexOf("?");
  if (qIndex < 0) return params;
  const qs = clean.slice(qIndex + 1);
  const parts = qs.split("&");
  for (const part of parts) {
    if (!part) continue;
    const eq = part.indexOf("=");
    const rawKey = eq < 0 ? part : part.slice(0, eq);
    const rawVal = eq < 0 ? "" : part.slice(eq + 1);
    try {
      const k = decodeURIComponent(rawKey.trim());
      const v = decodeURIComponent(rawVal.trim().replace(/\+/g, "%20"));
      if (k) params[k] = v;
    } catch {
      const k = rawKey.trim();
      const v = rawVal.trim();
      if (k) params[k] = v;
    }
  }
  return params;
}

export function isValidVpa(val) {
  if (val === undefined || val === null) return false;
  const str = String(val).trim();
  return /^[^\s@]+@[^\s@]+$/.test(str);
}

export function isPositiveAmount(val) {
  if (val === undefined || val === null || val === "") return false;
  const num = Number(String(val).replace(/,/g, "").trim());
  return Number.isFinite(num) && num > 0;
}

export function formatUpiAmount(val) {
  if (val === undefined || val === null || val === "") return "";
  const num = Number(String(val).replace(/,/g, "").trim());
  return Number.isFinite(num) && num > 0 ? num.toFixed(2) : "";
}

/**
 * Validates whether a final UPI URI conforms to NPCI requirements:
 * 1. starts with upi://pay?
 * 2. contains pa (valid VPA)
 * 3. contains positive numeric am
 */
export function validateBackendUpiUrl(upiUrl) {
  if (!upiUrl || typeof upiUrl !== "string") return false;
  const trimmed = upiUrl.trim().replace(/&amp;/gi, "&");
  if (!/^upi:\/\/pay\?/i.test(trimmed)) return false;
  const params = parseUpiUriParams(trimmed);
  if (!isValidVpa(params.pa)) return false;
  if (!isPositiveAmount(params.am)) return false;
  return true;
}

/**
 * Recursively extracts backend UPI payment information from the order response.
 * Safely handles null, arrays, nested objects, stringified JSON, and circular references.
 * Prefers complete UPI URIs over reconstructing one.
 */
export function extractBackendPaymentData(root, fallbackAmount = null) {
  const result = {
    upiUrl: "",
    upiId: "",
    vpa: "",
    amount: "",
    transactionId: "",
    merchantName: "",
    transactionNote: "",
    merchantCode: "",
    currency: "",
    source: "",
    params: {},
  };

  if (!root || (typeof root !== "object" && typeof root !== "string")) {
    return result;
  }

  const queue = [{ value: root, path: "response", depth: 0 }];
  const visited = new Set();

  const uriCandidates = [];
  const vpaCandidates = [];
  const amountCandidates = [];
  const transactionCandidates = [];
  const merchantCandidates = [];
  const noteCandidates = [];
  const codeCandidates = [];
  const currencyCandidates = [];

  while (queue.length > 0) {
    const { value, path, depth } = queue.shift();
    if (value === null || value === undefined || depth > 12) continue;

    if (typeof value === "string") {
      const trimmed = value.trim().replace(/&amp;/gi, "&");
      if (/^upi:\/\/pay\?/i.test(trimmed)) {
        uriCandidates.push({ value: trimmed, path, score: 200 - depth });
      } else if (
        (trimmed.startsWith("{") && trimmed.endsWith("}")) ||
        (trimmed.startsWith("[") && trimmed.endsWith("]"))
      ) {
        try {
          const parsed = JSON.parse(trimmed);
          if (parsed && typeof parsed === "object") {
            queue.push({ value: parsed, path: `${path}(parsed)`, depth: depth + 1 });
          }
        } catch {
          // Ignore parse errors.
        }
      }
      continue;
    }

    if (typeof value !== "object") continue;
    if (visited.has(value)) continue;
    visited.add(value);

    const entries = Array.isArray(value)
      ? value.map((v, i) => [String(i), v])
      : Object.entries(value);

    for (const [rawKey, child] of entries) {
      if (child === null || child === undefined) continue;
      const childPath = `${path}.${rawKey}`;
      const normKey = normalizePaymentFieldKey(rawKey);
      const isContextMatch = /(payment|upi|pay|order|delivery|transaction|qr|merchant)/i.test(childPath);
      const score = (isContextMatch ? 30 : 0) - depth;

      if (typeof child === "string" || typeof child === "number" || typeof child === "boolean") {
        const text = String(child).trim().replace(/&amp;/gi, "&");

        // 1. Complete UPI URI
        if (typeof child === "string" && /^upi:\/\/pay\?/i.test(text)) {
          uriCandidates.push({ value: text, path: childPath, score: score + 200 });
        } else if (
          typeof child === "string" &&
          ((text.startsWith("{") && text.endsWith("}")) || (text.startsWith("[") && text.endsWith("]")))
        ) {
          try {
            const parsed = JSON.parse(text);
            if (parsed && typeof parsed === "object") {
              queue.push({ value: parsed, path: `${childPath}(parsed)`, depth: depth + 1 });
            }
          } catch {
            // Ignore
          }
        }

        if (BACKEND_UPI_URI_KEYS.has(normKey) && typeof child === "string" && /^upi:\/\/pay\?/i.test(text)) {
          uriCandidates.push({ value: text, path: childPath, score: score + 250 });
        }

        // 2. VPA / UPI ID
        if (isValidVpa(text)) {
          let vpaScore = score;
          if (BACKEND_UPI_VPA_KEYS.has(normKey)) {
            vpaScore += 100;
            if (normKey === "deliveryupiid" || normKey === "deliveryvpa") vpaScore += 30;
            if (normKey === "upiid" || normKey === "vpa" || normKey === "upivpa") vpaScore += 20;
          }
          vpaCandidates.push({ value: text, path: childPath, score: vpaScore });
        }

        // 3. Amount
        if (isPositiveAmount(child)) {
          if (BACKEND_PAYMENT_AMOUNT_KEYS.has(normKey)) {
            let amtScore = score + 50;
            if (normKey === "netbill" || normKey === "payableamount") amtScore += 30;
            if (normKey === "paymentamount" || normKey === "amount") amtScore += 20;
            if (normKey === "totalamount" || normKey === "total_amount") amtScore += 10;
            amountCandidates.push({ value: child, path: childPath, score: amtScore });
          }
        }

        // 4. Transaction Reference
        if (BACKEND_TRANSACTION_KEYS.has(normKey) && text && text !== "0" && text !== "-1") {
          transactionCandidates.push({ value: text, path: childPath, score: score + 50 });
        }

        // 5. Merchant / Payee Name
        if (typeof child === "string" && BACKEND_MERCHANT_NAME_KEYS.has(normKey) && text) {
          merchantCandidates.push({ value: text, path: childPath, score: score + 50 });
        }

        // 6. Transaction Note
        if (typeof child === "string" && BACKEND_TRANSACTION_NOTE_KEYS.has(normKey) && text) {
          noteCandidates.push({ value: text, path: childPath, score: score + 50 });
        }

        // 7. Merchant Code
        if (BACKEND_MERCHANT_CODE_KEYS.has(normKey) && text) {
          codeCandidates.push({ value: text, path: childPath, score: score + 50 });
        }

        // 8. Currency
        if (BACKEND_CURRENCY_KEYS.has(normKey) && text) {
          currencyCandidates.push({ value: text, path: childPath, score: score + 50 });
        }
      } else if (typeof child === "object") {
        queue.push({ value: child, path: childPath, depth: depth + 1 });
      }
    }
  }

  const bestAmtCandidate = amountCandidates.sort((a, b) => b.score - a.score)[0] || null;
  const bestAmountVal = bestAmtCandidate?.value !== undefined ? bestAmtCandidate.value : fallbackAmount;
  const effectiveAmount = formatUpiAmount(bestAmountVal);

  const bestTxn = transactionCandidates.sort((a, b) => b.score - a.score)[0]?.value || "";
  const bestMerchant = merchantCandidates.sort((a, b) => b.score - a.score)[0]?.value || "";
  const bestNote = noteCandidates.sort((a, b) => b.score - a.score)[0]?.value || "";
  const bestCode = codeCandidates.sort((a, b) => b.score - a.score)[0]?.value || "";
  const bestCurrency = currencyCandidates.sort((a, b) => b.score - a.score)[0]?.value || "";

  // -------------------------------------------------------------
  // A. PREFER COMPLETE BACKEND UPI URI
  // -------------------------------------------------------------
  if (uriCandidates.length > 0) {
    uriCandidates.sort((a, b) => {
      const aParams = parseUpiUriParams(a.value);
      const bParams = parseUpiUriParams(b.value);
      const aComplete = isValidVpa(aParams.pa) && isPositiveAmount(aParams.am);
      const bComplete = isValidVpa(bParams.pa) && isPositiveAmount(bParams.am);
      if (aComplete && !bComplete) return -1;
      if (!aComplete && bComplete) return 1;
      return (b.score || 0) - (a.score || 0);
    });

    for (const cand of uriCandidates) {
      const params = parseUpiUriParams(cand.value);
      if (isValidVpa(params.pa)) {
        if (isPositiveAmount(params.am)) {
          // Complete UPI URI already has valid pa and positive am. Use it directly!
          result.upiUrl = cand.value;
          result.upiId = params.pa;
          result.vpa = params.pa;
          result.amount = formatUpiAmount(params.am);
          result.transactionId = params.tr || bestTxn || "";
          result.merchantName = params.pn || bestMerchant || "";
          result.transactionNote = params.tn || bestNote || "";
          result.merchantCode = params.mc || bestCode || "";
          result.currency = params.cu || bestCurrency || "INR";
          result.source = cand.path;
          result.params = parseUpiUriParams(cand.value);
          return result;
        } else if (effectiveAmount) {
          // Complete URI provided by backend but missing am; supplement only authoritative am
          const sep = cand.value.includes("?") ? (cand.value.endsWith("?") ? "" : "&") : "?";
          const finalUri = `${cand.value}${sep}am=${effectiveAmount}`;
          result.upiUrl = finalUri;
          result.upiId = params.pa;
          result.vpa = params.pa;
          result.amount = effectiveAmount;
          result.transactionId = params.tr || bestTxn || "";
          result.merchantName = params.pn || bestMerchant || "";
          result.transactionNote = params.tn || bestNote || "";
          result.merchantCode = params.mc || bestCode || "";
          result.currency = params.cu || bestCurrency || "INR";
          result.source = `${cand.path} + backend amount (${bestAmtCandidate?.path || "order total"})`;
          result.params = parseUpiUriParams(finalUri);
          return result;
        }
      }
    }
  }

  // -------------------------------------------------------------
  // B. BUILD FROM BACKEND PAYMENT FIELDS
  // -------------------------------------------------------------
  const bestVpa = vpaCandidates.sort((a, b) => b.score - a.score)[0] || null;
  if (bestVpa?.value && effectiveAmount) {
    const queryParts = [];
    queryParts.push(`pa=${bestVpa.value}`);
    if (bestMerchant) queryParts.push(`pn=${encodeURIComponent(bestMerchant).replace(/%20/g, "+")}`);
    queryParts.push(`am=${effectiveAmount}`);
    queryParts.push(`cu=${encodeURIComponent(bestCurrency || "INR")}`);
    if (bestTxn) queryParts.push(`tr=${encodeURIComponent(bestTxn)}`);
    if (bestNote) {
      queryParts.push(`tn=${encodeURIComponent(bestNote).replace(/%20/g, "+")}`);
    } else if (bestTxn) {
      queryParts.push(`tn=${encodeURIComponent(`Payment for ${bestTxn}`).replace(/%20/g, "+")}`);
    }
    if (bestCode) queryParts.push(`mc=${encodeURIComponent(bestCode)}`);

    const finalUri = `upi://pay?${queryParts.join("&")}`;
    result.upiUrl = finalUri;
    result.upiId = bestVpa.value;
    result.vpa = bestVpa.value;
    result.amount = effectiveAmount;
    result.transactionId = bestTxn;
    result.merchantName = bestMerchant;
    result.transactionNote = bestNote;
    result.merchantCode = bestCode;
    result.currency = bestCurrency || "INR";
    result.source = `${bestVpa.path} + ${bestAmtCandidate?.path || "order total"}`;
    result.params = parseUpiUriParams(finalUri);
    return result;
  }

  return result;
}

export function buildBackendUpiPaymentUrl(paymentData, fallbackAmount = null) {
  return extractBackendPaymentData(paymentData, fallbackAmount);
}

export function validateBackendUpiPaymentUrl(paymentData, fallbackAmount = null) {
  const result = buildBackendUpiPaymentUrl(paymentData, fallbackAmount);
  if (!validateBackendUpiUrl(result?.upiUrl)) {
    throw new Error(
      "The backend did not return a complete UPI payment request. Expected a UPI URI or backend payment fields including the delivery UPI ID."
    );
  }
  return result;
}
