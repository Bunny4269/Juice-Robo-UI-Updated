/**
 * Validates the raw UPI URL generated by the backend.
 * The backend owns the UPI payload: do not strip, rewrite, normalize,
 * or invent gateway parameters.
 */
export function normalizeBackendUpiUrl(value) {
  const raw = String(value ?? "").trim().replace(/&amp;/gi, "&");
  if (!raw || !/^upi:\/\/pay\?/i.test(raw)) return "";
  return raw;
}

/**
 * Extracts query string from upi://pay?... URL preserving byte-for-byte all parameters.
 */
export function getUpiQueryString(backendUpiUrl) {
  const genericUrl = normalizeBackendUpiUrl(backendUpiUrl);
  if (!genericUrl) return "";
  const queryIndex = genericUrl.indexOf("?");
  if (queryIndex < 0) return "";
  return genericUrl.slice(queryIndex + 1).trim();
}

/**
 * Android UPI URL constructor:
 * - Supports generic upi://pay?... Intent
 * - Supports Android-specific Intent URI syntax for installed apps
 * - Strictly does NOT double-encode the query payload
 * - Fallback to generic upi://pay if specific app package is not installed
 */
export function buildAndroidUpiUrl(backendUpiUrl, appId) {
  const query = getUpiQueryString(backendUpiUrl);
  if (!query) return "";

  const app =
    UPI_APPS.find((a) => a.id === String(appId || "").toLowerCase()) || {
      id: "generic",
    };

  // For "Other UPI apps" / Generic: use the standard generic upi://pay?... Intent
  if (app.id === "generic" || !app.androidPackage) {
    const fallbackUrl = encodeURIComponent(`upi://pay?${query}`);
    return `intent://pay?${query}#Intent;scheme=upi;S.browser_fallback_url=${fallbackUrl};end`;
  }

  // Standard Android Intent URI syntax:
  // intent://pay?<raw_query>#Intent;scheme=upi;package=<pkg>;S.browser_fallback_url=<fallback>;end
  // Notice: raw query is passed directly without double-encoding.
  const fallbackUrl = encodeURIComponent(`upi://pay?${query}`);
  return `intent://pay?${query}#Intent;scheme=upi;package=${app.androidPackage};S.browser_fallback_url=${fallbackUrl};end`;
}

/**
 * iOS UPI URL constructor:
 * - Does NOT use Android Intent syntax
 * - For PhonePe: uses standards-compatible upi://pay to prevent "Verification Failed"
 * - For other apps: uses registered iOS URL scheme
 * - Preserves every provider parameter without double-encoding or stripping
 */
export function buildIosUpiUrl(backendUpiUrl, appId) {
  const query = getUpiQueryString(backendUpiUrl);
  if (!query) return backendUpiUrl || "";

  const app =
    UPI_APPS.find((a) => a.id === String(appId || "").toLowerCase()) || {
      id: "generic",
    };

  // For generic / Other UPI apps: use standard upi://pay?...
  if (app.id === "generic") {
    return `upi://pay?${query}`;
  }

  const scheme = app.iosScheme || "upi://pay";
  const cleanScheme = String(scheme).trim().replace(/:+$/, "").replace(/\/+$/, "");

  // Preserve the exact provider-generated query byte-for-byte without modification
  return `${cleanScheme}?${query}`;
}

/**
 * Platform-aware UPI URL builder.
 */
export function buildPlatformUpiUrl(backendUpiUrl, appId, isAndroid = isAndroidDevice) {
  if (isAndroid) {
    return buildAndroidUpiUrl(backendUpiUrl, appId);
  }
  return buildIosUpiUrl(backendUpiUrl, appId);
}

/**
 * Launches the constructed UPI URL using the appropriate mechanism:
 * - iOS Safari: window.location.assign(url)
 * - Android: window.location.href = url
 */
export function launchUpiPaymentUrl(url, isIOS = isIOSDevice) {
  if (!url) throw new Error("UPI payment link is unavailable.");
  if (isIOS) {
    window.location.assign(url);
  } else {
    window.location.href = url;
  }
  return true;
}

/**
 * Automatic cross-platform UPI launcher:
 * - Automatically detects the operating system (Android, iOS, or Desktop).
 * - Android: Launches the generic Android UPI chooser Intent (intent://pay?<query>#Intent;scheme=upi;end)
 *            allowing the user to choose from all installed UPI apps natively without hardcoding.
 * - iOS: Attempts to open the backend upi://pay?... URI directly without requiring platform/app selection.
 *        Monitors whether an app responds and invokes onNoHandler if no handler exists so the user isn't stuck.
 * - Desktop: Invokes onDesktop callback without triggering unregistered protocol handler console errors.
 */
export function launchCrossPlatformUpi(upiUrl, { onNoHandler, onDesktop } = {}) {
  if (!upiUrl) {
    throw new Error("UPI payment link is unavailable.");
  }

  // 1. Desktop / Non-mobile check
  if (!isMobileDevice) {
    if (typeof onDesktop === "function") {
      onDesktop();
    }
    return false;
  }

  // 2. Android: Generic Intent Chooser
  if (isAndroidDevice) {
    const query = getUpiQueryString(upiUrl);
    const fallback = encodeURIComponent(upiUrl);
    const androidChooserIntent = query
      ? `intent://pay?${query}#Intent;scheme=upi;S.browser_fallback_url=${fallback};end`
      : upiUrl;

    try {
      window.location.href = androidChooserIntent;
      return true;
    } catch (err) {
      console.warn("[Juice Robo] Android Intent chooser failed, falling back to direct upi:// URI", err);
      window.location.href = upiUrl;
      return true;
    }
  }

  // 3. iOS: Native upi://pay?... launch with fallback detection
  if (isIOSDevice) {
    let appOpened = false;

    const handleHandoff = () => {
      appOpened = true;
    };

    window.addEventListener("pagehide", handleHandoff, { once: true });
    window.addEventListener("blur", handleHandoff, { once: true });

    const handleVisibility = () => {
      if (document.visibilityState === "hidden") {
        appOpened = true;
      }
    };
    document.addEventListener("visibilitychange", handleVisibility, { once: true });

    try {
      window.location.href = upiUrl;
    } catch (err) {
      console.error("[Juice Robo] iOS UPI launch error:", err);
      if (typeof onNoHandler === "function") {
        onNoHandler(err);
      }
      return false;
    }

    // Safety timeout: if page remains visible and focused, no UPI app handled the scheme
    window.setTimeout(() => {
      window.removeEventListener("pagehide", handleHandoff);
      window.removeEventListener("blur", handleHandoff);
      document.removeEventListener("visibilitychange", handleVisibility);

      if (!appOpened && document.visibilityState === "visible") {
        if (typeof onNoHandler === "function") {
          onNoHandler(new Error("No compatible UPI app detected."));
        }
      }
    }, 2500);

    return true;
  }

  // 4. Other mobile fallback
  window.location.href = upiUrl;
  return true;
}

/**
 * Persists pending payment session in BOTH localStorage and sessionStorage
 * so it survives browser return, app switching, and page reloads.
 */
export function persistPaymentSession(sessionData) {
  if (!sessionData) return;
  try {
    const json = JSON.stringify(sessionData);
    localStorage.setItem("juice_robo_payment_session", json);
    localStorage.setItem("juice_robo_pending_order_id", sessionData.orderId || "");
    localStorage.setItem("juice_robo_pending_cart_id", sessionData.cartId || "");
    if (sessionData.transactionId) {
      localStorage.setItem("juice_robo_pending_transaction_id", sessionData.transactionId);
    }
    if (sessionData.total) {
      localStorage.setItem("juice_robo_pending_amount", String(sessionData.total));
    }

    sessionStorage.setItem("juice_robo_payment_session", json);
    sessionStorage.setItem("juice_robo_pending_order_id", sessionData.orderId || "");
    sessionStorage.setItem("juice_robo_pending_cart_id", sessionData.cartId || "");
    if (sessionData.transactionId) {
      sessionStorage.setItem("juice_robo_pending_transaction_id", sessionData.transactionId);
    }
  } catch (e) {
    console.warn("[Juice Robo] Failed to persist payment session:", e);
  }
}

/**
 * Clears pending payment session from BOTH localStorage and sessionStorage.
 */
export function clearPaymentSession() {
  try {
    localStorage.removeItem("juice_robo_payment_session");
    localStorage.removeItem("juice_robo_pending_order_id");
    localStorage.removeItem("juice_robo_pending_cart_id");
    localStorage.removeItem("juice_robo_pending_transaction_id");
    localStorage.removeItem("juice_robo_pending_amount");

    sessionStorage.removeItem("juice_robo_payment_session");
    sessionStorage.removeItem("juice_robo_pending_order_id");
    sessionStorage.removeItem("juice_robo_pending_cart_id");
    sessionStorage.removeItem("juice_robo_pending_transaction_id");
    sessionStorage.removeItem("juice_robo_pending_amount");
    sessionStorage.removeItem("juice_robo_pending_upi_url");
    sessionStorage.removeItem("juice_robo_pending_upi_id");
  } catch (e) {
    console.warn("[Juice Robo] Failed to clear payment session:", e);
  }
}

